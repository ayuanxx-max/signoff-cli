// argparse-shaped errors, so a failed command reads the same as the Python
// reference (message on stderr, exit 2, nothing on stdout).
const USAGE = "usage: signoff guard [-h] {init,guard,hook,status,uninstall} ...";
const HOOK_USAGE = "usage: signoff guard hook [-h] {pre-commit,commit-msg,pre-push}";
const INIT_USAGE =
  "usage: signoff guard init [-h] [--test-cmd TEST_CMD] [--budget BUDGET]\n" +
  "                          [--docs [DOCS ...]] [--no-ci] [--no-push]\n" +
  "                          [--prepare] [--lock-test] [--reset-install] [--share]\n" +
  "                          [--quiet] [--dry-run]";

function argparseError(usage, prog, body) {
  process.stderr.write(`${usage}\n`);
  process.stderr.write(`${prog}: error: ${body}\n`);
  return 2;
}

function usageError(body) {
  return argparseError(USAGE, "signoff guard", body);
}

function isInitPositionalError(args) {
  return args.docs === undefined && args._.length > 0;
}

function main(argv) {
  const args = core.parseArgs(argv || [], {});
  const cmd = args._.shift();
  try {
    if (cmd === "init") {
      // argparse raises "unrecognized arguments" from the top-level parser,
      // so the usage line is the parent's, not the subparser's.
      if (isInitPositionalError(args)) return usageError(`unrecognized arguments: ${args._.join(" ")}`);
      return cmdInit(normalizeInit(args));
    }
    if (cmd === "guard") return cmdGuard(args);
    if (cmd === "hook") return cmdHook(args);
    if (cmd === "status") return cmdStatus(args);
    if (cmd === "uninstall") {
      if (args._.length) return usageError(`unrecognized arguments: ${args._.join(" ")}`);
      return cmdUninstall(args);
    }
    if (!cmd) return usageError("the following arguments are required: cmd");
    return usageError(
      `argument cmd: invalid choice: '${cmd}' (choose from 'init', 'guard', 'hook', 'status', 'uninstall')`
    );
  } catch (e) {
    if (e instanceof GuardExit) {
      // repoRoot() fails closed: same one-line message and exit 1 as the Python guard.
      process.stderr.write(`${e.message}\n`);
      return e.code;
    }
    if (e instanceof ArgparseError) return argparseError(INIT_USAGE, "signoff guard init", e.message);
    throw e;
  }
}

// `--docs` takes zero or more values in the Python reference (argparse nargs="*").
// init has no positionals of its own, so any left-over words belong to --docs.
function normalizeInit(args) {
  const rawBudget = args.budget;
  let budget = null;
  if (rawBudget === true) throw new ArgparseError("argument --budget: expected one argument");
  if (rawBudget !== undefined) {
    budget = Number(rawBudget);
    if (!Number.isFinite(budget)) throw new ArgparseError(`argument --budget: invalid float value: '${rawBudget}'`);
  }
  if (args.testCmd === true) throw new ArgparseError("argument --test-cmd: expected one argument");
  const out = {
    testCmd: typeof args.testCmd === "string" ? args.testCmd : null,
    lockTest: !!args.lockTest,
    resetInstall: !!args.resetInstall,
    budget,
    docs: null,
    noCi: !!args.noCi,
    noPush: !!args.noPush,
    chain: !!args.chain,
    prepare: !!args.prepare,
    quiet: !!args.quiet,
    dryRun: !!args.dryRun,
    share: !!args.share,
    sign: !!args.sign,
    preset: args.preset ? String(args.preset) : null,
    editor: args.editor ? String(args.editor) : null,
  };
  if (args.docs !== undefined) {
    const list = Array.isArray(args.docs) ? args.docs.slice() : args.docs === true ? [] : [String(args.docs)];
    out.docs = list.concat(args._.map(String));
    if (out.docs.length === 0) out.docs = null; // `--docs` alone: argparse -> []
  }
  return out;
}

